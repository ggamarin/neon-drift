// Латиница, совпадающая по начертанию с кириллицей.
const LAT = { A: 'А', B: 'В', C: 'С', E: 'Е', H: 'Н', K: 'К', M: 'М', O: 'О', P: 'Р', T: 'Т', X: 'Х' };

const FONT = {};
(function compileFont() {
  for (const ch in GLYPHS) {
    const rows = GLYPHS[ch].split('/'), runs = [];
    let w = 1;
    rows.forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        if (row[x] !== '#') { x++; continue; }
        let n = 1;
        while (row[x + n] === '#') n++;
        runs.push(x, y, n);
        w = Math.max(w, x + n);
        x += n;
      }
    });
    FONT[ch] = { w, runs };
  }
  for (const k in LAT) FONT[k] = FONT[LAT[k]];
})();

const LINE_H = 10;
function glyph(ch) { return FONT[ch] || FONT[ch.toUpperCase()] || FONT['?']; }

function textW(str, scale) {
  let w = 0;
  for (const ch of str) w += ch === ' ' ? 4 : glyph(ch).w + 1;
  return Math.max(0, w - 1) * (scale || 1);
}

function drawText(c, str, x, y, color, scale) {
  const k = scale || 1;
  c.fillStyle = PAL[color];
  for (const ch of str) {
    if (ch === ' ') { x += 4 * k; continue; }
    const g = glyph(ch), r = g.runs;
    for (let i = 0; i < r.length; i += 3) c.fillRect(x + r[i] * k, y + r[i + 1] * k, r[i + 2] * k, k);
    x += (g.w + 1) * k;
  }
  return x;
}

// Перенос по словам под ширину в пикселях.
function wrapText(str, maxW) {
  const out = [];
  let line = '';
  for (const word of str.split(' ')) {
    const t = line ? line + ' ' + word : word;
    if (line && textW(t) > maxW) { out.push(line); line = word; } else line = t;
  }
  if (line) out.push(line);
  return out;
}
